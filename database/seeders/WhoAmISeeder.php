    {
        $questions = self::questions();

        $adminId = Question::query()->getConnection()->table('users')->orderBy('id')->value('id');

        $count = 0;
        foreach ($questions as $q) {
            $exists = Question::where('answer_a', $q['answer_a'])->whereNotNull('hint_1')->exists();
            if (!$exists) {
                Question::create(array_merge($q, [
                    'category_id' => 1,
                    'created_by' => $adminId,
                    
                    'correct_answer' => 'a',
                    'difficulty' => 'very_hard',
                    'points' => 750,
                    'status' => 'active',
                ]));
                $count++;
            }
        }
        $this->command->info("✅ تم إضافة $count سؤال");
    }

